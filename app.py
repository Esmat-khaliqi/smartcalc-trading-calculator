class App:
    def plus (self,num_1,num_2):
        result_plus = num_1 + num_2
        return result_plus
    
    def minus (self,num_1,num_2):
        result_plus = num_1 - num_2
        return result_plus
    
    def multiplication (self,num_1,num_2):
        result_plus = num_1 * num_2
        return result_plus
    
    def divide (self,num_1,num_2):
        result_plus = num_1 / num_2
        return result_plus
    
    def percent (self,num_1,num_2):
        price = num_1
        prc = num_2
        result = price * prc / 100
        result_plus = price - result
        return result_plus
            